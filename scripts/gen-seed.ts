// Generates supabase/seed.sql from the TypeScript content bank (single source of truth).
// Run: npm run seed:gen   (Node >= 22.6 with native type stripping)
// The seed contains reference content only (skills, items without answers, approved built-in exercises). No child data.
import { writeFileSync } from 'node:fs';
import { SKILLS } from '../lib/content/skills.ts';
import { ITEMS } from '../lib/content/items.seed.ts';
import { SEED_EXERCISE_SETS } from '../lib/content/exercises.seed.ts';

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const j = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;

const lines: string[] = [
  '-- GENERATED by scripts/gen-seed.ts. Do not edit by hand.',
  '-- Reference content only. Assessment answers are NOT stored in the database.',
  'begin;',
  'insert into skills (id, strand, sequence, name, objective) values',
  SKILLS.map((s) => `  (${q(s.id)}, ${q(s.strand)}, ${s.sequence}, ${q(s.name)}, ${q(s.objective)})`).join(',\n') +
    '\non conflict (id) do update set name = excluded.name, objective = excluded.objective;',
  '',
  'insert into assessment_items (id, skill_id, difficulty, type, content) values',
  ITEMS.map((i) => `  (${q(i.id)}, ${q(i.skillId)}, ${i.difficulty}, ${q(i.type)}, ${j(i.content)})`).join(',\n') +
    '\non conflict (id) do update set content = excluded.content, type = excluded.type, difficulty = excluded.difficulty;',
  '',
  "insert into exercises (id, skill_id, difficulty, language, content, source, validation, review_status, created_by) values",
  SEED_EXERCISE_SETS.map((s) =>
    `  (md5(${q(s.id)})::uuid, ${q(s.skillId)}, ${s.difficulty}, 'en', ${j({ seedId: s.id, items: s.items })}, 'seed', ${j({ note: 'built-in set, checked by unit test against validate.ts' })}, 'approved', null)`,
  ).join(',\n') + '\non conflict (id) do update set content = excluded.content;',
  'commit;',
  '',
];

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), lines.join('\n'));
console.log(`seed.sql: ${SKILLS.length} skills, ${ITEMS.length} items, ${SEED_EXERCISE_SETS.length} exercise sets`);
